            'PostalStreet' => $this->postalStreet,
            'PostalCity' => $this->postalCity,
            'PostalPostcode' => $this->postalPostcode,
            'PostalState' => $this->postalState,
            'Note' => $this->note,
            'ID_Sex' => $this->idSex,
            'Birthday' => $this->birthday,
            'BirthdayYear' => $this->birthdayYear,
            'IsForeign' => $this->isForeign,
